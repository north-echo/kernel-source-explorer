  await expect(page.locator('.relationships-pane')).toBeHidden();
  await expect(page.getByRole('complementary',{name:'Checkpoint compiler graph'})).toBeVisible();
  await expect(page.locator('.checkpoint-graph-links')).toContainText('begin_new_exec → do_close_on_exec');
  await page.getByRole('button',{name:'Hide checkpoint graph'}).click();
  await expect(page.locator('.checkpoint-graph')).toHaveCount(0);
  await page.getByRole('button',{name:'Show checkpoint graph'}).click();
  await page.locator('.checkpoint-graph-links button').first().click();
  await expect(page.locator('.source-line.current')).toContainText('do_close_on_exec(me->files)');
  const graphBox=await page.locator('.checkpoint-graph').boundingBox();
  const sourceBox=await page.locator('.source-pane').boundingBox();
